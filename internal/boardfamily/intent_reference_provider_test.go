func TestReferencedProviderKnownPromptsSyntheticResponses(t *testing.T) {
	t.Setenv("OPENAI_API_KEY", "offline-referenced-placeholder")
	t.Setenv("KICADAI_AI_MODEL", "must-not-override-pinned-model")
	minimum, maximum := 24000, 0
	for _, tc := range referencedSyntheticCases() {
		t.Run(tc.id, func(t *testing.T) {
			prompt := retainedTypedSelection(t, tc.id).OriginalRequest
			raw := syntheticReferencedIntent(t, tc.facts...)
			ledger := filepath.Join(t.TempDir(), "ledger.json")
			calls := 0
			transport := roundTripperFunc(func(r *http.Request) (*http.Response, error) {
				calls++
				if calls != 1 {
					t.Fatal("automatic retry")
				}
				size := checkReferencedProviderRequest(t, r, prompt)
				minimum, maximum = min(minimum, size), max(maximum, size)
				return referencedProviderResponse(t, raw, "complete", "offline-"+tc.id), nil
			})
			s, err := interpretReferencedWithTransport(context.Background(), prompt, ledger, LedgerPolicy{"offline-referenced-case", 1, 50000}, transport)
			if err != nil || calls != 1 || s.Outcome != "decision" || s.Decision.Disposition != tc.disposition || !strings.Contains(s.Decision.Message, tc.reason) {
				t.Fatalf("unexpected local synthetic outcome: %+v %v", s, err)
			}
			if !bytes.Equal(s.RawIntent, raw) || len(s.RawDecision) != 0 || s.OriginalRequest != prompt || s.AdmissionVersion != ReferenceIntentVersion || s.ResponseID != "offline-"+tc.id || s.Usage.TotalTokens != 300 {
				t.Fatal("source, raw response, protocol or response identity was lost")
			}
			request, _ := PrepareReferencedRequest(prompt)
			if !reflect.DeepEqual(s.RequestClauses, request.Clauses) || !reflect.DeepEqual(s.SourceQuantities, request.Quantities) {
				t.Fatal("application-owned source table was changed")
			}
			if tc.disposition == "supported" {
				want := Config{"1", tc.family, tc.profile, 3.2, 3.4, 1000, 10, 35, tc.capacitance}
				if s.Decision.Configuration == nil || *s.Decision.Configuration != want {
					t.Fatalf("wrong config: %+v", s.Decision.Configuration)
				}
				checkReferencedGeneratedBundle(t, *s.Decision.Configuration)
			} else if s.Decision.Configuration != nil {
				t.Fatal("non-design outcome exposes a configuration")
			}
			l := readReferencedTestLedger(t, ledger)
			if len(l.Entries) != 1 || l.Entries[0].Status != "completed" || l.Entries[0].ResponseID != s.ResponseID || l.Entries[0].ReserveMicroUSD != 50000 || l.Entries[0].EstimatedMicroUSD != 360 {
				t.Fatal("synthetic accounting is incomplete or allowance was refunded")
			}
		})
	}
	t.Logf("14 known prompts, synthetic responses; actual encoded request sizes %d–%d bytes", minimum, maximum)
}

// The provider output feeds the real deterministic generator, not a simulated
// generator. Compare every file it creates to the existing reviewed example.
// This does not execute the CLI, KiCad validation or manufacturing export; those
// unchanged qualifications are authenticated separately and are not re-scored.
func checkReferencedGeneratedBundle(t *testing.T, c Config) {
	t.Helper()
	for _, key := range []string{"OPENAI_API_KEY", "ANTHROPIC_API_KEY", "GEMINI_API_KEY", "GOOGLE_API_KEY"} {
		t.Setenv(key, "")
	}
	family := "bmp280"
	if c.Family == FamilySHT31 {
		family = "sht31"
	}
	published := filepath.Join("..", "..", "examples", "board-family-v2", family+"-"+c.Profile)
	generated := filepath.Join(t.TempDir(), "generated")
	if _, err := Generate(c, generated); err != nil {
		t.Fatal(err)
	}
	compared := 0
	err := filepath.WalkDir(generated, func(path string, entry os.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		rel, err := filepath.Rel(generated, path)
		if err != nil {
			return err
		}
		got, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		want, err := os.ReadFile(filepath.Join(published, rel))
		if err != nil {
			return err
		}
		if !bytes.Equal(got, want) {
			return fmt.Errorf("indexed extraction changed reviewed %s/%s", family+"-"+c.Profile, rel)
		}
		compared++
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("synthetic provider → real generator: %s/%s, all %d generated files byte-identical to reviewed example", family, c.Profile, compared)
}

func TestReferencedProviderFailureOutcomesAndAccounting(t *testing.T) {
	for _, mode := range []string{"invalid-extraction", "malformed-json", "transport-failure", "incomplete", "refusal", "wrong-model", "redirect", "rate-limit", "usage-exceeds-reserve", "settlement-lock"} {
		t.Run(mode, func(t *testing.T) {
			t.Setenv("OPENAI_API_KEY", "offline-referenced-placeholder")
			prompt := "Please use BMP280 with fast profile."
			raw := syntheticReferencedIntent(t, referencedChoice("sensor", "BMP280", "required", 0), referencedChoice("profile", "fast", "required", 0))
			if mode == "invalid-extraction" {
				raw = []byte(`{"version":"wrong-version","facts":[]}`)
			} else if mode == "malformed-json" {
				raw = []byte(`{"not":`)
			}
			ledger := filepath.Join(t.TempDir(), "ledger.json")
			calls := 0
			transport := roundTripperFunc(func(r *http.Request) (*http.Response, error) {
				calls++
				checkReferencedProviderRequest(t, r, prompt)
				if calls > 1 {
					t.Fatal("retry or redirect reached transport")
				}
				if mode == "transport-failure" {
					return nil, errors.New("synthetic offline transport failure")
				}
				if mode == "settlement-lock" {
					if err := os.Mkdir(ledger+".lock", 0700); err != nil {
						t.Fatal(err)
					}
				}
				if mode == "redirect" {
					return &http.Response{StatusCode: 307, Header: http.Header{"Location": []string{"https://not-approved.invalid/"}}, Body: io.NopCloser(strings.NewReader(""))}, nil
				}
				if mode == "rate-limit" {
					return &http.Response{StatusCode: 429, Header: http.Header{}, Body: io.NopCloser(strings.NewReader(`{"error":{"message":"synthetic rate limit"}}`))}, nil
				}
				return referencedProviderResponse(t, raw, mode, "offline-failure"), nil
			})
			s, err := interpretReferencedWithTransport(context.Background(), prompt, ledger, LedgerPolicy{"offline-referenced-failure", 1, 50000}, transport)
			if err == nil || calls != 1 || s.Decision.Configuration != nil {
				t.Fatalf("error was ignored or replayed: %+v %v, calls=%d", s, err, calls)
			}
			outcome, ledgerStatus := "provider_failed_or_unknown", "failed_or_unknown"
			switch mode {
			case "invalid-extraction", "malformed-json":
				outcome, ledgerStatus = "invalid_extraction", "completed"
			case "incomplete":
				outcome = "provider_incomplete"
			case "refusal":
				outcome, ledgerStatus = "provider_refusal", "completed"
			case "wrong-model":
				outcome, ledgerStatus = "model_mismatch", "completed"
			case "usage-exceeds-reserve":
				outcome, ledgerStatus = "accounting_failure", "completed"
			case "settlement-lock":
				outcome, ledgerStatus = "accounting_failure", "reserved_unknown_outcome"
			}
			if s.Outcome != outcome {
				t.Fatalf("outcome=%s want=%s", s.Outcome, outcome)
			}
			l := readReferencedTestLedger(t, ledger)
			if len(l.Entries) != 1 || l.Entries[0].Status != ledgerStatus || l.Entries[0].ReserveMicroUSD != 50000 {
				t.Fatalf("incorrect final ledger: %+v", l)
			}
			if member(mode, "invalid-extraction", "wrong-model", "usage-exceeds-reserve", "settlement-lock") && !bytes.Equal(s.RawIntent, raw) {
				t.Fatal("completed structured response lost during later failure")
			}
			if mode == "usage-exceeds-reserve" && l.HaltReason == "" {
				t.Fatal("excessive usage did not halt the ledger")
			}
		})
	}
}

func TestReferencedProviderPreflightAndPayloadBounds(t *testing.T) {
	for _, mode := range []string{"cancelled", "no-key", "no-transport", "invalid-policy", "exhausted", "wrong-budget", "locked", "invalid-prompt", "ordinary-max", "escape-heavy", "quantity-heavy"} {
		t.Run(mode, func(t *testing.T) {
			t.Setenv("OPENAI_API_KEY", "offline-referenced-placeholder")
			prompt := "Please use BMP280."
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			policy := LedgerPolicy{"offline-referenced-preflight", 1, 50000}
			ledger := filepath.Join(t.TempDir(), "ledger.json")
			switch mode {
			case "cancelled":
				cancel()
			case "no-key":
				t.Setenv("OPENAI_API_KEY", "")
			case "invalid-policy":
				policy.MaxRequests = -1
			case "exhausted", "wrong-budget":
				if _, err := reserveWithPolicy(ledger, policy); err != nil {
					t.Fatal(err)
				}
				if mode == "wrong-budget" {
					policy.MaxRequests = 2
				}
			case "locked":
				if err := os.Mkdir(ledger+".lock", 0700); err != nil {
					t.Fatal(err)
				}
			case "invalid-prompt":
				prompt = " "
			case "ordinary-max":
				prompt = strings.Repeat("x", 2000)
			case "escape-heavy":
				prompt = strings.Repeat(`"`, 2000)
			case "quantity-heavy":
				prompt = strings.Repeat("1 V, ", 128)
			}
			before, _ := os.ReadFile(ledger)
			calls := 0
			var transport http.RoundTripper = roundTripperFunc(func(r *http.Request) (*http.Response, error) {
				calls++
				size := checkReferencedProviderRequest(t, r, prompt)
				t.Logf("%s: actual encoded payload %d bytes", mode, size)
				return nil, errors.New("synthetic offline stop")
			})
			if mode == "no-transport" {
				transport = nil
			}
			s, err := interpretReferencedWithTransport(ctx, prompt, ledger, policy, transport)
			if err == nil || s.Decision.Configuration != nil {
				t.Fatal("preflight/error did not withhold configuration")
			}
			wantCalls := 0
			if mode == "ordinary-max" {
				wantCalls = 1
			}
			if calls != wantCalls {
				t.Fatalf("calls=%d want=%d error=%v", calls, wantCalls, err)
			}
			if calls == 0 {
				if s.Outcome != "no_request" || s.LedgerIndex != 0 {
					t.Fatal("unsent request reported an attempted outcome")
				}
				after, _ := os.ReadFile(ledger)
				if !bytes.Equal(before, after) {
					t.Fatal("rejected request modified existing history")
				}
				if before == nil {
					if _, statErr := os.Stat(ledger); !os.IsNotExist(statErr) {
						t.Fatal("rejected request created a ledger")
					}
				}
			}
			t.Logf("%s: %s (%v)", mode, s.Outcome, err)
		})
	}
}

