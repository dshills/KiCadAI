func TestReferencedProviderSchemaContract(t *testing.T) {
	for _, counts := range [][2]int{{1, 0}, {3, 2}, {32, 128}} {
		schema := referencedIntentSchema(counts[0], counts[1])
		if schema["type"] != "object" || schema["anyOf"] != nil {
			t.Fatal("provider schema needs an object root, not root anyOf")
		}
		var check func(map[string]any)
		check = func(s map[string]any) {
			if union, ok := s["anyOf"].([]any); ok {
				for _, branch := range union {
					check(branch.(map[string]any))
				}
				return
			}
			switch s["type"] {
			case "object":
				if s["additionalProperties"] != false {
					t.Fatal("open provider object")
				}
				props := s["properties"].(map[string]any)
				var keys []string
				for key, child := range props {
					if member(key, "number", "quote", "configuration", "decision") {
						t.Fatalf("model can author prohibited field %s", key)
					}
					keys = append(keys, key)
					check(child.(map[string]any))
				}
				sort.Strings(keys)
				if !reflect.DeepEqual(keys, s["required"]) {
					t.Fatal("not all object fields are required")
				}
			case "array":
				check(s["items"].(map[string]any))
			case "string", "integer":
			default:
				t.Fatalf("unexpected schema type %v", s["type"])
			}
		}
		check(schema)
		root := schema["properties"].(map[string]any)
		branches := root["facts"].(map[string]any)["items"].(map[string]any)["anyOf"].([]any)
		seenNumber := false
		for _, branch := range branches {
			p := branch.(map[string]any)["properties"].(map[string]any)
			kind := p["kind"].(map[string]any)["enum"].([]string)[0]
			seenNumber = seenNumber || kind == "number"
			source := p["sources"].(map[string]any)
			if source["maxItems"] != counts[0] || source["items"].(map[string]any)["maximum"] != counts[0]-1 {
				t.Fatal("source bounds do not match this request")
			}
			q := p["quantities"].(map[string]any)
			if q["items"].(map[string]any)["maximum"] != max(0, counts[1]-1) || q["maxItems"].(int) > counts[1] {
				t.Fatal("quantity bounds do not match this request")
			}
			if counts[1] == 0 && q["maxItems"] != 0 {
				t.Fatal("quantity-free request permits invented quantity IDs")
			}
		}
		if seenNumber != (counts[1] > 0) {
			t.Fatal("numeric branch must exist only when literal quantities exist")
		}
	}
	if !reflect.DeepEqual(ReferencedIntentSchema(), referencedIntentSchema(32, 128)) {
		t.Fatal("exported schema blueprint diverged")
	}
}

// This parses the actual HTTP payload generated by aiprovider.OpenAIProvider.
// It is never sent to a socket: every caller installs an in-memory transport.
func checkReferencedProviderRequest(t testing.TB, r *http.Request, prompt string) int {
	t.Helper()
	if r.Method != "POST" || r.URL.String() != "https://api.openai.com/v1/responses" || r.ContentLength <= 0 || r.ContentLength > 24000 {
		t.Fatal("endpoint/method/byte bounds changed")
	}
	body, err := io.ReadAll(r.Body)
	if closeErr := r.Body.Close(); err != nil || closeErr != nil {
		t.Fatal(errors.Join(err, closeErr))
	}
	if bytes.Contains(body, []byte("offline-referenced-placeholder")) {
		t.Fatal("credential leaked into model input")
	}
	var payload struct {
		Model, Input              string
		MaxOutputTokens           int `json:"max_output_tokens"`
		Background, Store, Stream bool
		Text                      struct {
			Format struct {
				Type, Name string
				Strict     bool
				Schema     map[string]any
			}
		}
	}
	if err := json.Unmarshal(body, &payload); err != nil {
		t.Fatal(err)
	}
	if payload.Model != SelectionModel || payload.MaxOutputTokens != 1600 || payload.Background || payload.Store || !payload.Stream || !payload.Text.Format.Strict || payload.Text.Format.Type != "json_schema" || payload.Text.Format.Name != ReferenceIntentSchemaName {
		t.Fatal("provider model/streaming/schema/token restrictions changed")
	}
	var input struct {
		Prompt            string
		CapabilityContext string `json:"capability_context"`
		Attempt           int
		Diagnostics       []any
	}
	if err := json.Unmarshal([]byte(payload.Input), &input); err != nil {
		t.Fatal(err)
	}
	want, _, err := prepareReferencedGenerateRequest(prompt)
	if err != nil {
		t.Fatal(err)
	}
	if input.Prompt != want.Prompt || input.CapabilityContext != want.CapabilityContext || input.Attempt != 1 || len(input.Diagnostics) != 0 {
		t.Fatal("source/context changed or a recovery attempt was requested")
	}
	a, _ := json.Marshal(payload.Text.Format.Schema)
	b, _ := json.Marshal(want.OutputSchema)
	if !bytes.Equal(a, b) {
		t.Fatal("request-specific provider schema differs from its source contract")
	}
	return len(body)
}

func referencedProviderResponse(t testing.TB, raw []byte, mode, id string) *http.Response {
	return referencedProviderResponseForModel(t, raw, mode, id, SelectionModel)
}

func referencedProviderResponseForModel(t testing.TB, raw []byte, mode, id, model string) *http.Response {
	t.Helper()
	status := "completed"
	var incomplete any
	content := []any{map[string]any{"type": "output_text", "text": string(raw)}}
	inputTokens := 100
	if mode == "incomplete" {
		status, incomplete = "incomplete", map[string]any{"reason": "max_output_tokens"}
	}
	if mode == "wrong-model" {
		model = "not-the-approved-model"
	}
	if mode == "usage-exceeds-reserve" {
		inputTokens = 200000
	}
	if mode == "refusal" {
		content = []any{map[string]any{"type": "refusal", "refusal": "Synthetic provider refusal."}}
	}
	response := map[string]any{"id": id, "model": model, "status": status, "error": nil, "incomplete_details": incomplete,
		"output": []any{map[string]any{"type": "message", "status": "completed", "content": content}},
		"usage":  map[string]any{"input_tokens": inputTokens, "output_tokens": 200, "total_tokens": inputTokens + 200}}
	event := "response." + status
	b, err := json.Marshal(map[string]any{"type": event, "response": response})
	if err != nil {
		t.Fatal(err)
	}
	return &http.Response{StatusCode: 200, Header: http.Header{"Content-Type": []string{"text/event-stream"}},
		Body: io.NopCloser(strings.NewReader("event: " + event + "\ndata: " + string(b) + "\n\n"))}
}

