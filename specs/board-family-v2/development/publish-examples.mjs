function inventory(dir, prefix='') {
  const files=[];
  for (const entry of fs.readdirSync(path.join(dir,prefix),{withFileTypes:true})) {
    const rel=path.join(prefix,entry.name);
    assert.equal(entry.isSymbolicLink(),false,'no symlinks');
    if(entry.isDirectory())files.push(...inventory(dir,rel));
    else if(!entry.name.endsWith('.kicad_prl') && !entry.name.startsWith('~'))files.push(rel);
  }
  return files.sort();
}
function addition(file, bytes) {
  const text=bytes.toString('utf8'); assert.ok(Buffer.from(text).equals(bytes),'publication supports exact UTF-8 assets');
  assert.ok(!bytes.length || text.endsWith('\n'),`missing terminal newline: ${file}`);
  return `*** Add File: ${file}\n`+(text ? text.slice(0,-1).split('\n').map(l=>'+'+l).join('\n')+'\n' : '');
}
